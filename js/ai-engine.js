// Безопасное вычисление мат. выражения
function safeEval(expr) {
  // разрешаем только цифры, скобки, +-*/%^., и функции Math
  const sanitized = expr.replace(/[^0-9+\-*/().,%\s^]/g, "").trim();
  if (!sanitized) throw new Error("пустое выражение");
  // заменяем ^ на **, % оставляем, , на .
  let js = sanitized.replace(/\^/g, "**").replace(/,/g, ".");
  // проверка на валидность: не должно быть подряд операторов кроме **
  if (/[^0-9)\s]\s*[^0-9(*\s\-+/*%.\s]/.test(js)) {} // allow
  // вычисляем в изолированном Function
  // eslint-disable-next-line no-new-func
  const fn = new Function(`return (${js})`);
  const res = fn();
  if (typeof res !== "number" || !isFinite(res)) throw new Error("не число");
  return { expr: sanitized, result: res, js };
}

function extractExpression(text) {
  // ищем математическое выражение: "сколько будет 2+2*2", "вычисли (3+5)/2"
  const m = text.match(/([0-9][0-9\s+\-*/().,%^]*[0-9\)])/);
  if (m) return m[1];
  // fallback: всё после "равно", "будет", "="
  const m2 = text.match(/(?:равно|будет|=)\s*([0-9+\-*/().,%^\s]+)/i);
  if (m2) return m2[1];
  return null;
}

function escapeHtml(s) {
  return s.replace(/&/g,"&amp;").replace(/</g,"&lt;").replace(/>/g,"&gt;");
}

