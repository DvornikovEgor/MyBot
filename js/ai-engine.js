export class MyBotAI {
  constructor(opts = {}) {
    this.model = MODELS[opts.model] || MODELS["mybot-pro"];
    this.temperature = opts.temperature ?? 0.85;
    this.systemPrompt = opts.systemPrompt || this.model.system;
    this.history = []; // {role, content}
    this.lastTopic = null;
    this.musicHandler = opts.musicHandler || null;
  }

  setModel(modelId) {
    this.model = MODELS[modelId] || this.model;
  }
  setMusicHandler(fn) { this.musicHandler = fn; }

  // Основной генератор — возвращает полный текст (собирает стрим)
  async generate(userText, { onChunk, signal } = {}) {
    let full = "";
    for await (const chunk of this.stream(userText, { signal })) {
      full += chunk;
      if (onChunk) onChunk(chunk, full);
    }
    return full;
  }

  // Потоковый генератор — yield кусочков текста
  async *stream(userText, { signal } = {}) {
    const lang = detectLang(userText);
    const intent = detectIntent(userText);
    const rng = new Rng(hashString(userText + "|" + this.history.length + "|" + this.model.id));

    // сохраняем в историю
    this.history.push({ role: "user", content: userText });
    if (this.history.length > 24) this.history = this.history.slice(-24);
    this.lastTopic = extractTopic(userText);

    // выбираем генератор ответа
    let rawAnswer = "";
    switch (intent) {
      case "greeting": rawAnswer = genGreeting(rng, lang, this.history.length); break;
      case "identity": rawAnswer = genIdentity(rng, lang); break;
      case "farewell": rawAnswer = genFarewell(rng, lang); break;
      case "math": rawAnswer = genMath(userText, rng, lang); break;
      case "code": rawAnswer = genCode(userText, rng, lang); break;
      case "creative": rawAnswer = genCreative(userText, rng, lang); break;
      case "translate": rawAnswer = genTranslate(userText, rng, lang); break;
      case "music_control": rawAnswer = genMusicControl(userText, rng, this.musicHandler); break;
      case "explain":
      case "general":
      default: rawAnswer = genGeneral(userText, rng, lang); break;
    }

    // для reason-модели добавляем блок размышлений
    let finalAnswer = rawAnswer;
    let thinking = "";
    if (this.model.id === "mybot-reason") {
      thinking = this._genThinking(userText, intent, rng, lang);
      finalAnswer = `<thinking>\n${thinking}\n</thinking>\n\n${rawAnswer}`;
    }

    // Добавляем в историю ассистента (без thinking для контекста)
    this.history.push({ role: "assistant", content: rawAnswer });

    // Стримим по кусочкам, имитируя токены
    const chunks = this._chunkText(finalAnswer, rng);
    for (const c of chunks) {
      if (signal && signal.aborted) break;
      // небольшая вариативность задержки от температуры
      const base = this.model.speed;
      const jitter = rng.float(0.6, 1.6) * (this.temperature * 10 + 5);
      const delay = Math.max(4, base + jitter + (c.includes("\n") ? 30 : 0));
      await new Promise(r => setTimeout(r, delay));
      yield c;
    }
  }

  _genThinking(userText, intent, rng, lang) {
    const steps = lang==="en"
      ? [
        `User intent: ${intent}. Need to decide answer structure.`,
        `Key entities: "${this.lastTopic}". Check KB for direct hit.`,
        `If KB hit → use structured answer; else synthesize 3-paragraph explanation.`,
        `Language: ${lang}. Tone: friendly, helpful, concise but thorough.`,
        `Add follow-up question to keep conversation flowing.`
      ]
      : [
        `Интент пользователя: ${intent}. Выбираю структуру ответа.`,
        `Ключевая тема: «${this.lastTopic}». Проверяю базу знаний на точное совпадение.`,
        `Если есть в KB → даю структурированный ответ с заголовками/кодом. Если нет — синтезирую 3 абзаца: определение → детали → примеры/вывод.`,
        `Язык: ${lang}. Тон: дружелюбно, по делу, чуть с юмором, без воды.`,
        `В конце добавлю подсказку, что спросить дальше, чтобы удержать диалог.`
      ];
    // перемешиваем порядок чуть-чуть для живости
    const order = rng.shuffle(steps);
    return order.map((s,i)=>`${i+1}. ${s}`).join("\n");
  }

  _chunkText(text, rng) {
    // режем на куски по 2-6 символов (имитация токенов), но не рвём внутри слова сильно
    const chunks = [];
    let i = 0;
    while (i < text.length) {
      const len = rng.int(2, 6);
      // стараемся резать по границе слова/пунктуации
      let end = Math.min(i + len, text.length);
      // если внутри слова — расширим до конца слова иногда
      if (end < text.length && /[a-zа-яё0-9]/i.test(text[end]) && /[a-zа-яё0-9]/i.test(text[end-1]) && rng.chance(0.6)) {
        while (end < text.length && /[a-zа-яё0-9]/i.test(text[end])) end++;
      }
      chunks.push(text.slice(i, end));
      i = end;
    }
    return chunks;
  }

  clear() {
    this.history = [];
    this.lastTopic = null;
  }

  exportHistory() {
    return JSON.stringify(this.history, null, 2);
  }

  importHistory(json) {
    try {
      const arr = JSON.parse(json);
      if (Array.isArray(arr)) this.history = arr.slice(-50);
    } catch {}
  }
}

// Хелпер для внешнего использования: быстрый ответ без инстанса
export async function quickAnswer(text, modelId = "mybot-pro") {
  const ai = new MyBotAI({ model: modelId });
  return await ai.generate(text);
}
