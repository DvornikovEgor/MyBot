function genMath(text, rng, lang) {
  const exprRaw = extractExpression(text);
  if (!exprRaw) {
    // пробуем уравнение вида 2x+5=15
    const eq = text.match(/([0-9xX+\-*/=.\s]+=[0-9xX+\-*/.\s]+)/);
    if (eq) {
      return genEquation(eq[1], rng, lang);
    }
    return lang==="en"
      ? `Send me an expression like \`2 + 2 * 2\` or an equation like \`2x + 5 = 15\`, I'll solve it step-by-step.`
      : `Кидай выражение вроде \`2 + 2 * 2\` или уравнение \`2x + 5 = 15\` — решу по шагам.`;
  }
  try {
    const {expr, result} = safeEval(exprRaw);
    const steps = [];
    // показываем порядок действий упрощённо
    if (expr.includes("*") || expr.includes("/")) {
      steps.push(`1. Сначала умножение/деление: \`${expr}\``);
      steps.push(`2. Потом сложение/вычитание.`);
    } else {
      steps.push(`1. Вычисляю слева направо: \`${expr}\``);
    }
    steps.push(`3. **Ответ: \`${result}\`**`);
    if (Number.isInteger(result) && Math.abs(result) < 10000) {
      steps.push(`\n_Проверка:_ ${result} — ${result % 2===0 ? "чётное" : "нечётное"}${result>0?" положительное":""}.`);
    }
    const intro = lang==="en" ? `### Math solved` : `### Решено`;
    return `${intro}\n\n**Выражение:** \`${expr}\`\n\n${steps.join("\n")}\n\nХочешь — решу уравнение, проценты или задачу текстом.`;
  } catch (e) {
    return lang==="en"
      ? `Couldn't evaluate \`${exprRaw}\` — check the syntax. Example: \`(3+5)*2 / 4\`.`
      : `Не смог посчитать \`${exprRaw}\` — проверь запись. Пример: \`(3+5)*2 / 4\`.`;
  }
}

function genEquation(eqStr, rng, lang) {
  // простая линейка ax + b = c
  const m = eqStr.replace(/\s/g,"").match(/^([0-9]*\.?[0-9]*)x([+\-][0-9.]+)?=([0-9.\-]+)$/i);
  if (!m) return `Уравнение \`${eqStr}\` пока не распарсил — скинь попроще вроде \`2x+5=15\`.`;
  const a = m[1]==="" || m[1]==="+" ? 1 : m[1]==="-" ? -1 : parseFloat(m[1]);
  const b = m[2] ? parseFloat(m[2]) : 0;
  const c = parseFloat(m[3]);
  const x = (c - b) / a;
  return `### Решение уравнения\n\n\`${a}x ${b>=0?`+ ${b}`:`- ${Math.abs(b)}`} = ${c}\`\n\n1. Переносим \`${b}\` → \`${a}x = ${c} - (${b}) = ${c-b}\`\n2. Делим на \`${a}\` → \`x = ${c-b} / ${a} = ${x}\`\n\n**Ответ: x = ${x}**\n\nПроверка: ${a}*${x} ${b>=0?`+ ${b}`:`- ${Math.abs(b)}`} = ${a*x+b} ✅`;
}

