function findKB(text) {
  const qTokens = tokenize(text);
  if (qTokens.length === 0) return null;
  const qSet = new Set(qTokens);
  const norm = normalize(text);
  let best = null;
  let bestScore = 0;
  for (const {entry, tokens} of KB_INDEX) {
    let score = 0;
    for (const t of qTokens) {
      if (tokens.has(t)) score += 2;
      // частичное только для длинных слов и без ложных срабатываний на аббревиатуры
      for (const kt of tokens) {
        if (kt.length > 4 && t.length > 4 && kt !== t && (kt.startsWith(t) || t.startsWith(kt))) { score += 1; break; }
      }
    }
    // бонус за точное совпадение ключевой фразы как токенов, а не подстроки внутри слова (чтобы "js" не матчил "json")
    for (const kw of entry.keywords) {
      const kwTokens = tokenize(kw);
      if (kwTokens.length === 0) continue;
      if (kwTokens.length === 1) {
        if (qSet.has(kwTokens[0])) score += 3;
      } else {
        // мультислово: проверяем вхождение как подстроки с границами слов
        const kwNorm = normalize(kw);
        // ищем фразу целиком
        if (norm.includes(kwNorm)) {
          // проверяем что это не внутри более длинного слова: требуем границы
          const re = new RegExp(`(^|[^a-zа-я0-9])${kwNorm.replace(/[.*+?^${}()|[\]\\]/g,'\\$&')}([^a-zа-я0-9]|$)`);
          if (re.test(norm)) score += 3;
        }
      }
    }
    if (score > bestScore) {
      bestScore = score;
      best = entry;
    }
  }
  return bestScore >= 2 ? best : null;
}

function extractTopic(text) {
  // эвристика: берём существительные после "про", "о", "такое", "что такое"
  let m = text.match(/(?:что такое|что значит|расскажи (?:про|о)|объясни)\s+([^?.!,\n]{2,60})/i);
  if (m) return m[1].trim().replace(/[?.!]+$/,"");
  // иначе — самые длинные слова
  const toks = tokenize(text).filter(w => w.length > 3);
  if (toks.length === 0) return text.slice(0, 40).trim();
  // берём 2 самых характерных слова
  const uniq = [...new Set(toks)].sort((a,b)=>b.length - a.length).slice(0,2);
  return uniq.join(" ");
}

