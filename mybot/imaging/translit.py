"""Транслитерация кириллицы в латиницу для подписей.

Встроенный растровый шрифт содержит только латиницу и цифры, поэтому русские
подписи преобразуются в латинскую запись (ГОСТ-подобная схема).
"""

from __future__ import annotations

_MAP = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e",
    "ж": "zh", "з": "z", "и": "i", "й": "y", "к": "k", "л": "l", "м": "m",
    "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
    "ф": "f", "х": "h", "ц": "ts", "ч": "ch", "ш": "sh", "щ": "sch",
    "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya",
}


def transliterate(text: str) -> str:
    """Заменить кириллицу латиницей; остальные символы оставить как есть."""
    out = []
    for ch in text:
        low = ch.lower()
        if low in _MAP:
            rep = _MAP[low]
            out.append(rep.upper() if ch.isupper() else rep)
        else:
            out.append(ch)
    return "".join(out)
