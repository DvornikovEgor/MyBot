GLYPH_WIDTH = 5
GLYPH_HEIGHT = 7


def glyph_columns(ch: str) -> List[int]:
    return _GLYPHS.get(ch.upper(), _GLYPHS["?"])


def text_width(text: str, scale: int = 1, spacing: int = 1) -> int:
    if not text:
        return 0
    per = (GLYPH_WIDTH + spacing) * scale
    return per * len(text) - spacing * scale


def draw_text(canvas, text: str, x: int, y: int, color, scale: int = 2,
              spacing: int = 1, alpha: float = 1.0) -> int:
    """Нарисовать строку. Возвращает x правого края."""
    cursor = x
    for ch in text:
        cols = glyph_columns(ch)
        for cx, bits in enumerate(cols):
            for by in range(GLYPH_HEIGHT):
                if bits & (1 << (GLYPH_HEIGHT - 1 - by)):
                    px = cursor + cx * scale
                    py = y + by * scale
                    if scale == 1:
                        canvas.set_pixel(px, py, color, alpha)
                    else:
                        canvas.rect(px, py, px + scale, py + scale, color, alpha)
        cursor += (GLYPH_WIDTH + spacing) * scale
    return cursor


def draw_text_centered(canvas, text: str, cx: int, y: int, color, scale: int = 2,
                       spacing: int = 1, alpha: float = 1.0) -> None:
    w = text_width(text, scale, spacing)
    draw_text(canvas, text, int(cx - w / 2), y, color, scale, spacing, alpha)
